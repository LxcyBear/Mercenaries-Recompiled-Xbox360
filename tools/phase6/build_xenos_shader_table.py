#!/usr/bin/env python3
"""Generate a typed hash-keyed Xenos shader table from offline-compiled blobs."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

KINDS = {
    "vertex": "MERC360_SHADER_VERTEX",
    "combiner_pixel": "MERC360_SHADER_COMBINER_PIXEL",
}
HEX64 = re.compile(r"^(?:0x)?([0-9a-fA-F]{1,16})$")


def key64(value, label: str) -> int:
    if isinstance(value, int):
        if 0 <= value <= 0xFFFFFFFFFFFFFFFF:
            return value
        raise ValueError(f"{label}: out of uint64 range")
    m = HEX64.match(str(value))
    if not m:
        raise ValueError(f"{label}: invalid uint64 key")
    return int(m.group(1), 16)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest", type=Path)
    ap.add_argument("output", type=Path)
    args = ap.parse_args()

    manifest_path = args.manifest.resolve()
    root = manifest_path.parent
    doc = json.loads(manifest_path.read_text(encoding="utf-8"))
    if doc.get("version") != 1:
        raise SystemExit("shader manifest version must be 1")
    entries = doc.get("entries")
    if not isinstance(entries, list):
        raise SystemExit("entries must be a list")

    seen = set()
    rows = []
    blobs = []
    for index, entry in enumerate(entries):
        kind = entry.get("kind")
        if kind not in KINDS:
            raise SystemExit(f"entry {index}: unsupported kind {kind!r}")
        semantic = key64(entry.get("semantic_key"), f"entry {index} semantic_key")
        source = key64(entry.get("source_hash"), f"entry {index} source_hash")
        identity = (kind, semantic)
        if identity in seen:
            raise SystemExit(
                f"entry {index}: duplicate typed semantic key {kind}:0x{semantic:016X}"
            )
        seen.add(identity)

        relative = entry.get("blob")
        if not isinstance(relative, str) or not relative:
            raise SystemExit(f"entry {index}: blob missing")
        path = (root / relative).resolve()
        try:
            path.relative_to(root)
        except ValueError:
            raise SystemExit(f"entry {index}: blob escapes manifest directory")
        data = path.read_bytes()
        expected = entry.get("sha256")
        actual = sha256(data)
        if expected is not None and str(expected).lower() != actual:
            raise SystemExit(f"entry {index}: blob SHA256 mismatch")

        symbol = f"merc360_shader_blob_{index:04d}"
        blobs.append(
            f"static const unsigned char {symbol}[] = {{\n"
            + ",".join(f"0x{b:02X}" for b in data)
            + "\n};\n"
        )
        rows.append(
            "    { "
            + KINDS[kind]
            + f", 0x{semantic:016X}ULL, 0x{source:016X}ULL, "
            + symbol
            + f", {len(data)}u }},"
        )

    out = """/* Generated by build_xenos_shader_table.py. Do not edit. */
#include <stdint.h>

enum Merc360ShaderKind {
    MERC360_SHADER_VERTEX = 1,
    MERC360_SHADER_COMBINER_PIXEL = 2
};

struct Merc360ShaderEntry {
    Merc360ShaderKind kind;
    uint64_t semantic_key;
    uint64_t source_hash;
    const unsigned char *bytecode;
    uint32_t bytecode_size;
};

"""
    out += "\n".join(blobs)
    out += "\nstatic const Merc360ShaderEntry g_merc360_shader_table[] = {\n"
    out += "\n".join(rows)
    out += "\n};\n"
    out += (
        "static const uint32_t g_merc360_shader_table_count = "
        "(uint32_t)(sizeof(g_merc360_shader_table) / "
        "sizeof(g_merc360_shader_table[0]));\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(out, encoding="utf-8")
    print(f"PASS: generated {len(rows)} typed Xenos shader entries -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
